_USER_OK = re.compile(r"^[A-Za-z0-9_.@\-]+$")   # rejects quotes/spaces so nothing can break out of the SQL string


def _bind_sql(roster: pd.DataFrame, n_spares: int) -> tuple[str, list[str]]:
    """Attendee + spare section of the setup script, for the roster typed into the editor."""
    problems, rows, seen = [], [], set()
    for i, r in enumerate(roster.fillna("").to_dict("records"), start=1):
        user = str(r.get("Snowflake user", "")).strip()
        name = str(r.get("Lab name", "")).strip().upper()
        if not user and not name:
            continue
        if not user:
            problems.append(f"Row {i}: Snowflake user is missing.")
            continue
        if not _USER_OK.match(user):
            problems.append(f"Row {i}: `{user}` - user names may only contain letters, digits and _ . @ -")
            continue
        if not name:
            name = re.sub(r"[^A-Z0-9_]", "", user.split("@")[0].split(".")[0].upper())[:20] or f"ATTENDEE{i:02d}"
        if not re.fullmatch(r"[A-Z0-9_]{1,20}", name) or name.startswith("SPARE"):
            problems.append(f"Row {i}: lab name `{name}` must be 1-20 letters, digits or _ and not start with SPARE.")
            continue
        if name in seen:
            problems.append(f"Row {i}: lab name `{name}` is used twice.")
            continue
        seen.add(name)
        rows.append({"user": user, "name": name})
    if not rows:
        problems.append("Enter at least one attendee.")
    if problems:
        return "", problems
    users_in = ", ".join(f"'{r['user'].upper()}'" for r in rows)
    first, second = rows[0]["name"], (rows[1]["name"] if len(rows) > 1 else None)
    parts = [
        "-- Borrowell Product Insights Agent lab | create attendee workspaces (generated by the guide)",
        "-- User defaults are NOT changed - attendees run USE ROLE themselves.",
        "USE ROLE PI_LAB_ADMIN;",
        "USE WAREHOUSE PI_LAB_WH;",
        "",
        f"-- 1. Check the users exist: expect {len(rows)} row(s); a missing user = fix the name first",
        "SHOW USERS;",
        'SELECT "name" FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))',
        f' WHERE UPPER("name") IN ({users_in});',
        "",
        "-- 2. Schema LAB_<NAME> + role PI_LAB_<NAME>, granted to each user (~2 s each)",
        f"CALL BORROWELL_AGENT_LAB.ADMIN.SETUP_ALL(PARSE_JSON($${json.dumps(rows, indent=2)}$$));",
        "",
    ]
    if n_spares:
        parts += [f"-- 3. Spares for walk-ins (on the day: CALL BORROWELL_AGENT_LAB.ADMIN.CLAIM_SPARE('<USER>');)",
                  f"CALL BORROWELL_AGENT_LAB.ADMIN.SETUP_SPARES({n_spares});", ""]
    parts += ["-- 4. Confirm everyone is ASSIGNED", "SELECT * FROM BORROWELL_AGENT_LAB.ADMIN.V_ROSTER;", "",
              f"-- 5. Smoke test as {first}",
              f"USE ROLE PI_LAB_{first}; USE SECONDARY ROLES NONE; USE WAREHOUSE PI_LAB_WH;",
              "SELECT COUNT(*) FROM BORROWELL_AGENT_LAB.DATA.TELEMETRY_EVENTS;   -- about 586K",
              f"CREATE OR REPLACE VIEW BORROWELL_AGENT_LAB.LAB_{first}.SMOKE_TEST AS SELECT 1 x;   -- must succeed",
              f"DROP VIEW BORROWELL_AGENT_LAB.LAB_{first}.SMOKE_TEST;"]
    if second:
        parts.append(f"-- Optional isolation check (run on its own - it must FAIL with not authorized):\n-- CREATE VIEW BORROWELL_AGENT_LAB.LAB_{second}.SMOKE_TEST AS SELECT 1 x;")
    parts += ["USE ROLE PI_LAB_ADMIN;", "", "-- Tell each attendee their lab name:"]
    parts += [f"--   {r['user']:<30} -> {r['name']}   (USE ROLE PI_LAB_{r['name']};)" for r in rows]
    return "\n".join(parts), []


def _full_setup_sql(bind_sql: str) -> str:
    banner = "-- " + "=" * 77
    parts = [f"{banner}\n-- Borrowell Product Insights Agent lab | LAB SETUP (generated)\n"
             f"-- Run top to bottom in ONE Snowsight worksheet as ACCOUNTADMIN (Run All). About 1 minute.\n{banner}"]
    for title, body in [("00_admin_setup.sql", sql_file("00_admin_setup.sql")), ("01_data.sql", sql_file("01_data.sql")),
                        ("02_attendee_procs.sql", sql_file("02_attendee_procs.sql")), ("create attendees", bind_sql)]:
        parts.append(f"\n{banner}\n-- >>> {title}\n{banner}\n{body.strip()}\n")
    return "\n".join(parts)


